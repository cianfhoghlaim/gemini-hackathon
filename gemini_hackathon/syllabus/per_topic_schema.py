# The 5 NCCA Key Competencies (used in the skill_domain default for every LO).
NCCA_KEY_COMPETENCIES: tuple[str, ...] = (
    "Communicating",
    "Being Creative",
    "Working with Others",
    "Managing Information & Thinking",
    "Managing Myself",
    "Staying Well",
)


@dataclass(frozen=True)
class CurriculumConcept:
    """A single per-topic asset schema (one per NCCA LO)."""

    subject: str  # "mathematics"
    topic: str  # "Differentiation & Integration"
    lo_code: str  # "LC-MATH-LO-023"
    lo_text: str  # the canonical NCCA LO description
    strand: str | None  # "Calculus" (Maths only)
    bloom_level: str  # "apply"
    skill_domains: list[str]  # ["Managing Information & Thinking", ...]
    visual_cue: str  # from SUBJECT_SPECIALITIES[subject]
    diagram_type: str  # from SUBJECT_SPECIALITIES[subject]
    complexity: str  # "moderate"
    palette_primary: str  # from themes/_official_guidelines
    palette_accent: str
    typography_stack: list[str]
    descriptor_vocabulary: list[str]
    ncca_citation: tuple[str, int] | None  # (pdf_filename, page_number)

    def to_asset_request_payload(self) -> dict[str, Any]:
        """Return the dict payload for the existing AssetControlRecord format."""
        return {
            "source_pdf_path": f"data/ireland/ncca_policy/{self.ncca_citation[0]}"
            if self.ncca_citation
            else "",
            "source_page": self.ncca_citation[1] if self.ncca_citation else 0,
            "learning_outcome_id": self.lo_code,
            "subject": self.subject,
            "palette_primary": self.palette_primary,
            "palette_secondary": self.palette_accent,
            "palette_accent": self.palette_accent,
            "palette_background": "#FAFAF7",
            "style": self.visual_cue.split(",")[0] if self.visual_cue else "illustration",
            "aspect_ratio": "16:9",
            "text_overlay": f"{self.subject.title()} - {self.topic}\n{self.lo_code}",
            "composition": "centered",
            "camera_angle": "front",
            "lighting": "natural",
            "fov_degrees": 50,
            "seed": None,
        }


def build_curriculum_concepts(
    *,
    subject: str,
    extracted_syllabus: Any,  # ExtractedSyllabus
    per_jurisdiction_palette: dict[str, str] | None = None,
) -> list[CurriculumConcept]:
    """Build the per-topic asset schema (one CurriculumConcept per LO).

    The expanded NCCA LO list (one per LCLearningOutcome in the
    extracted_syllabus) becomes the input to the 7-backend asset
    generation comparison (Phase 6).
    """
    speciality = SUBJECT_SPECIALITIES.get(subject, {})
    if per_jurisdiction_palette is None:
        per_jurisdiction_palette = {
            "primary": "#1a1a1a",
            "accent": "#CC4500",
        }

    concepts: list[CurriculumConcept] = []
    module_topics = getattr(extracted_syllabus, "module_topics", []) or []

    # Flatten every LO across every module
    for module in module_topics:
        if not isinstance(module, dict):
            continue
        module_name = module.get("name", "") or ""
        learning_outcomes = module.get("learning_outcomes", []) or []
        for lo in learning_outcomes:
            if not isinstance(lo, dict):
                continue
            lo_code = lo.get("code") or lo.get("lo_id") or f"STUB-{subject}-{len(concepts)}"
            lo_text = lo.get("title", "") or module_name
            bloom_level = lo.get("blooms_level", "apply") or "apply"

            # Strand (subject-specific)
            strand = lo.get("strand") or None

            # Skill domains (default to the 5 NCCA Key Competencies)
            skill_domains = lo.get("skill_domains") or list(NCCA_KEY_COMPETENCIES[:3])

            # NCCA citation (best-effort: pull from module if present, else None)
            ncca_citation = None
            if lo.get("ncca_url"):
                # e.g. 'LC-MATH-LO-023' → PDF + page (deterministic hash)
                page = (hash(lo_code) % 30) + 1  # mock page lookup
                ncca_citation = ("SC-L1-L2-Programme-Statement.pdf", page)

            concept = CurriculumConcept(
                subject=subject,
                topic=module_name,
                lo_code=str(lo_code),
                lo_text=str(lo_text),
                strand=str(strand) if strand else None,
                bloom_level=str(bloom_level).lower(),
                skill_domains=list(skill_domains),
                visual_cue=str(speciality.get("visual_cue", "")),
                diagram_type=str(speciality.get("diagram_type_default", "diagram")),
                complexity=str(speciality.get("complexity_default", "moderate")),
                palette_primary=per_jurisdiction_palette.get("primary", "#1a1a1a"),
                palette_accent=per_jurisdiction_palette.get("accent", "#CC4500"),
                typography_stack=["Arial", "Helvetica", "sans-serif"],
                descriptor_vocabulary=[
                    "Exceptional",
                    "Above expectations",
                    "In line with expectations",
                    "Yet to meet expectations",
                ],
                ncca_citation=ncca_citation,
            )
            concepts.append(concept)
    return concepts


