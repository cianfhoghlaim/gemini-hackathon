"""gemini_hackathon.syllabus.per_topic_schema — the per-topic asset schema (Phase 6 input).

The user's expanded ask: "develop per subject schemas for generating
assets per topic with syllabus and specialities of each subject and
compare those between assets generated by models and extraction methods".

This module converts `CurriculumUnit.learning_outcomes[i]` (the canonical
NCCA LO) into a `CurriculumConcept` — a typed per-topic asset schema
that captures:
  - the LO + topic + subject + strand + bloom level
  - the per-subject visual cue (from the lifted EDUCATION_FIBO_PROMPTS)
  - the per-subnation palette (from the lifted _official_guidelines)
  - the per-subject typography stack
  - the per-subject diagram conventions

Then converts `CurriculumConcept` -> `AssetRequest` (the existing cert
pipeline's AssetControlRecord format) so it can be fed directly to
the 7-backend image generation comparison (Phase 6).

Lifted + adapted from cianfhoghlaim/gemini_hackathon_assets_fibo/education_prompts.py:42-405
(the per-subject FIBO prompt bank) + the per-subject BAML extensions from
Phase 4.
"""

